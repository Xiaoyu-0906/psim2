"""Generate psim2/railtypes.hpp (the train types of SUMO's Rail car-following model) from
sumo-src/src/microsim/cfmodels/MSCFModel_Rail.h.

Upstream train data: Copyright (C) 2012-2026 German Aerospace Center (DLR)
and others. The generated file retains the upstream EPL-2.0 notice.

Usage: python3 tools/gen_railtypes.py [path/to/MSCFModel_Rail.h]
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "sumo-src", "src", "microsim", "cfmodels", "MSCFModel_Rail.h")
OUT = os.path.join(ROOT, "psim2", "railtypes.hpp")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("header", nargs="?", default=SRC)
    args = parser.parse_args()
    with open(args.header) as source:
        lines = source.read().splitlines()
    notice = lines[:next(i for i, line in enumerate(lines) if line.startswith("/// @file"))]
    if not any("SPDX-License-Identifier: EPL-2.0" in line for line in notice):
        raise ValueError("expected the SUMO copyright and license header")
    start = next(i for i, l in enumerate(lines) if re.match(r"\s*LinearApproxHelpers::LinearApproxMap init\w+\(\) const", l))
    end = next(i for i, l in enumerate(lines) if "initVehicleVariables" in l)
    body = []
    names = []
    for l in lines[start:end]:
        m = re.match(r"(\s*)(LinearApproxHelpers::LinearApproxMap|TrainParams) (init\w+)\(\) const \{(.*)$", l)
        if m:
            rtype = "LinearApproxMap" if m.group(2).startswith("Linear") else "TrainParams"
            names.append((rtype, m.group(3)))
            l = "inline %s %s() {%s" % (rtype, m.group(3), m.group(4))
        else:
            l = l[4:] if l.startswith("    ") else l
        l = l.replace("LinearApproxHelpers::LinearApproxMap", "LinearApproxMap").replace("LinearApproxHelpers::scalePoints", "scalePoints")
        body.append(l.rstrip())
    out = notice + ["// Generated by tools/gen_railtypes.py from SUMO 1.28 MSCFModel_Rail.h: the train types of the Rail",
           "// car-following model (traction and resistance curves in kN over m/s). Do not edit.",
           "#pragma once", "", "#include <map>", "", "namespace ps {", "namespace railtypes {", "",
           "using LinearApproxMap = std::map<double, double>;", "",
           "struct TrainParams {",
           "    double weight = 0;  // tons", "    double mf = 1;", "    double length = 0;", "    double decl = 0;",
           "    double vmax = 0;", "    double recovery = 0;", "    LinearApproxMap traction;  // m/s -> kN",
           "    LinearApproxMap resistance;  // m/s -> kN", "};", "",
           "// LinearApproxHelpers::scalePoints",
           "inline void scalePoints(LinearApproxMap& map, double keyFactor, double valueFactor) {",
           "    LinearApproxMap map2;", "    for (const auto& item : map) {",
           "        map2[item.first * keyFactor] = item.second * valueFactor;", "    }", "    map.swap(map2);", "}", ""]
    for rtype, name in names:
        out.append("inline %s %s();" % (rtype, name))
    out.append("")
    out += body
    out += ["}  // namespace railtypes", "}  // namespace ps", ""]
    open(OUT, "w").write("\n".join(out))
    print("wrote %s (%d functions)" % (OUT, len(names)))


if __name__ == "__main__":
    main()
